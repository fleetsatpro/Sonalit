-- Preserve operational records without inventing transporter contacts or driver credentials.
ALTER TABLE public.cds_drivers
  ALTER COLUMN phone DROP NOT NULL,
  ALTER COLUMN license_number DROP NOT NULL,
  ALTER COLUMN license_expiry DROP NOT NULL;

ALTER TABLE public.cds_transporters
  ALTER COLUMN contact_person DROP NOT NULL,
  ALTER COLUMN phone DROP NOT NULL;

-- Auto-created customers previously inherited company names and '-' as if they were contact details.
ALTER TABLE public.cds_customers
  ALTER COLUMN contact_person DROP NOT NULL,
  ALTER COLUMN phone DROP NOT NULL;

ALTER TABLE public.cds_drivers
  ADD COLUMN IF NOT EXISTS license_verification_status TEXT NOT NULL DEFAULT 'unverified',
  ADD COLUMN IF NOT EXISTS license_verified_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS license_verification_source TEXT;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.cds_drivers'::regclass
      AND conname = 'cds_drivers_license_verification_status_check'
  ) THEN
    ALTER TABLE public.cds_drivers
      ADD CONSTRAINT cds_drivers_license_verification_status_check
      CHECK (license_verification_status IN ('unverified','verified','rejected','expired','suspended'));
  END IF;
END $$;

-- This exact sentinel and its expiry were generated by the previous clamp path, not a licensing authority.
UPDATE public.cds_drivers
   SET license_number = NULL,
       license_expiry = NULL,
       license_verification_status = 'unverified',
       license_verified_at = NULL,
       license_verification_source = NULL
 WHERE upper(btrim(COALESCE(license_number, ''))) = 'PENDING';

-- The old clamp path stored '-' when a driver's phone was not supplied.
UPDATE public.cds_drivers SET phone = NULL WHERE phone = '-';

-- Auto-created customers used the same exact '-' phone sentinel; keep no phone as unknown.
UPDATE public.cds_customers
   SET contact_person = CASE WHEN contact_person = company_name THEN NULL ELSE contact_person END,
       phone = NULL
 WHERE phone = '-';

-- The exact transporter placeholder pair generated by the previous clamp path.
UPDATE public.cds_transporters
   SET contact_person = NULL, phone = NULL
 WHERE phone = '-'
   AND contact_person = company_name;

-- New manual lock records do not imply SecuriSat integration or provider verification.
-- Provider is a vendor identity, not a verification flag. Manual clamp does not
-- establish which vendor supplied the physical lock, so unknown stays NULL.
ALTER TABLE public.cds_electronic_locks
  ALTER COLUMN provider DROP NOT NULL,
  ALTER COLUMN provider DROP DEFAULT;


-- The control room resolves each trip to its authoritative booking-container row.
-- This partial index keeps that lookup bounded as the history grows.
CREATE INDEX IF NOT EXISTS idx_cds_booking_containers_trip
  ON public.cds_booking_containers(trip_id)
  WHERE trip_id IS NOT NULL AND deleted_at IS NULL;
